import { createHash } from 'node:crypto';

// ------------------------------------------------------------- tokens

function stripComments(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, '');
}

/** Index of the parenthesis closing the one at `open`. */
function closingParen(s, open) {
  let depth = 0;
  for (let i = open; i < s.length; i++) {
    if (s[i] === '(') depth++;
    else if (s[i] === ')') {
      depth--;
      if (depth === 0) return i;
    }
  }
  throw new Error('unbalanced parentheses in ' + s);
}

function splitTopLevel(s, sep = ',') {
  const out = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < s.length; i++) {
    if (s[i] === '(') depth++;
    else if (s[i] === ')') depth--;
    else if (s[i] === sep && depth === 0) {
      out.push(s.slice(start, i));
      start = i + 1;
    }
  }
  out.push(s.slice(start));
  return out.map((x) => x.trim());
}

/** Replaces every light-dark(a, b) in a value with a (which=0) or b (1). */
export function resolveLightDark(value, which) {
  let s = value;
  for (;;) {
    const i = s.indexOf('light-dark(');
    if (i < 0) return s.trim();
    const open = i + 'light-dark'.length;
    const close = closingParen(s, open);
    const args = splitTopLevel(s.slice(open + 1, close));
    if (args.length !== 2) throw new Error('light-dark() needs two values: ' + s);
    s = s.slice(0, i) + args[which] + s.slice(close + 1);
  }
}

/** Top-level rules of a stylesheet fragment: [{ prelude, body }]. */
function topLevelRules(css) {
  const rules = [];
  let i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) break;
    let depth = 0;
    let j = open;
    for (; j < css.length; j++) {
      if (css[j] === '{') depth++;
      else if (css[j] === '}') {
        depth--;
        if (depth === 0) break;
      }
    }
    rules.push({ prelude: css.slice(i, open).trim(), body: css.slice(open + 1, j) });
    i = j + 1;
  }
  return rules;
}

function declarations(body) {
  const out = [];
  for (const part of splitTopLevel(body, ';')) {
    const c = part.indexOf(':');
    if (c < 0) continue;
    out.push([part.slice(0, c).trim(), part.slice(c + 1).trim()]);
  }
  return out;
}

/**
 * Reads the design tokens of web/style.css (section "1. Design tokens").
 * Returns { light, dark, langRules } where light and dark map every custom
 * property to its value in that scheme (same keys in both) and langRules
 * are the per-language font rules, copied as they are.
 */
export function extractTokens(styleCss) {
  const start = styleCss.indexOf('1. Design tokens');
  const end = styleCss.indexOf('2. Base');
  if (start < 0 || end < 0 || end < start) throw new Error('web/style.css: token section not found');
  const section = stripComments(styleCss.slice(styleCss.indexOf('*/', start) + 2, styleCss.lastIndexOf('/*', end)));
  const light = {};
  const dark = {};
  const langRules = [];
  for (const rule of topLevelRules(section)) {
    if (rule.prelude === ':root') {
      for (const [k, v] of declarations(rule.body)) {
        if (!k.startsWith('--')) continue;
        light[k] = resolveLightDark(v, 0);
        dark[k] = resolveLightDark(v, 1);
      }
    } else if (/^\[lang\]|^:where\(/.test(rule.prelude) || rule.prelude.includes(':lang(')) {
      if (/light-dark\(|#[0-9a-f]{3,8}\b|rgb\(|hsl\(/i.test(rule.body)) throw new Error('colour in a language rule: ' + rule.prelude);
      langRules.push(`${rule.prelude.replace(/\s+/g, ' ')} {${rule.body.replace(/\s+/g, ' ')}}`);
    }
  }
  if (!light['--accent'] || !light['--bg-card']) throw new Error('web/style.css: expected tokens missing');
  return { light, dark, langRules };
}

/** tokens.css: the light set, the dark set under prefers-color-scheme. */
export function tokensCss({ light, dark, langRules }) {
  const block = (o) => Object.entries(o).map(([k, v]) => `  ${k}: ${v};`).join('\n');
  return [
    '/* SPDX-License-Identifier: AGPL-3.0-or-later */',
    '/* Copyright (C) 2026 LectureFlow contributors. Licensed under the GNU AGPL v3 or later; see LICENSE. */',
    '/* Generated by scripts/build.mjs from web/style.css (design tokens). Do not edit. */',
    `:root {\n  color-scheme: light;\n${block(light)}\n}`,
    `@media (prefers-color-scheme: dark) {\n:root {\n  color-scheme: dark;\n${block(dark)}\n}\n}`,
    ...langRules,
    '',
  ].join('\n');
}

export function tokensJs({ light, dark }) {
  return [
    '// SPDX-License-Identifier: AGPL-3.0-or-later',
    '// Copyright (C) 2026 LectureFlow contributors. Licensed under the GNU AGPL v3 or later; see LICENSE.',
    '// Generated by scripts/build.mjs from web/style.css (design tokens). Do not edit.',
    `export const tokens = ${JSON.stringify({ light, dark }, null, 2)};`,
    '',
  ].join('\n');
}

// --------------------------------------------------------------- PNG

const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

export function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
}

function adler32(buf) {
  let a = 1;
  let b = 0;
  for (const x of buf) {
    a = (a + x) % 65521;
    b = (b + a) % 65521;
  }
  return ((b << 16) | a) >>> 0;
}

/**
 * A zlib stream of stored (uncompressed) blocks. Unlike deflate proper it
 * is byte-for-byte the same under every Node and zlib version, so the
 * build is reproducible for AMO's source review; the icons stay small.
 */
export function zlibStored(data) {
  const parts = [Buffer.from([0x78, 0x01])];
  const MAX = 65535;
  let off = 0;
  do {
    const n = Math.min(MAX, data.length - off);
    const last = off + n >= data.length;
    const head = Buffer.alloc(5);
    head[0] = last ? 1 : 0;
    head.writeUInt16LE(n, 1);
    head.writeUInt16LE(~n & 0xffff, 3);
    parts.push(head, Buffer.from(data.buffer, data.byteOffset + off, n));
    off += n;
  } while (off < data.length);
  const sum = Buffer.alloc(4);
  sum.writeUInt32BE(adler32(data));
  parts.push(sum);
  return Buffer.concat(parts);
}

/** RGBA pixels (Uint8Array, width*height*4) → PNG bytes. */
export function encodePng(width, height, rgba) {
  const raw = Buffer.alloc((width * 4 + 1) * height);
  for (let y = 0; y < height; y++) {
    raw[y * (width * 4 + 1)] = 0;
    Buffer.from(rgba.buffer, rgba.byteOffset + y * width * 4, width * 4).copy(raw, y * (width * 4 + 1) + 1);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // RGBA
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlibStored(raw)),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

export function parseHexColor(hex) {
  const m = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(String(hex).trim());
  if (!m) throw new Error('not a hex colour: ' + hex);
  let h = m[1];
  if (h.length === 3) h = h.split('').map((c) => c + c).join('');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
}

// The app's mark (web/favicon.svg) on a 32-unit grid, flat: a rounded
// square in the accent colour with five bars.
const BARS = [[9, 13, 19], [13, 10, 22], [17, 8, 24], [21, 11, 21], [25, 14, 18]];

/** Renders the toolbar icon at `size` px (4×4 supersampling). */
export function renderIcon(size, bgHex, fgHex) {
  const bg = parseHexColor(bgHex);
  const fg = parseHexColor(fgHex);
  const ss = 4;
  const px = new Uint8Array(size * size * 4);
  const r = 8;
  const half = 1.2;
  const inRect = (x, y) => {
    if (x < 0 || y < 0 || x > 32 || y > 32) return false;
    const cx = x < r ? r : x > 32 - r ? 32 - r : x;
    const cy = y < r ? r : y > 32 - r ? 32 - r : y;
    return (x - cx) ** 2 + (y - cy) ** 2 <= r * r;
  };
  const inBar = (x, y) =>
    BARS.some(([bx, y1, y2]) => {
      const cy = Math.min(Math.max(y, y1), y2);
      return (x - bx) ** 2 + (y - cy) ** 2 <= half * half;
    });
  for (let py = 0; py < size; py++) {
    for (let pxl = 0; pxl < size; pxl++) {
      let a = 0;
      const acc = [0, 0, 0];
      for (let i = 0; i < ss; i++) {
        for (let j = 0; j < ss; j++) {
          const x = ((pxl + (j + 0.5) / ss) / size) * 32;
          const y = ((py + (i + 0.5) / ss) / size) * 32;
          if (!inRect(x, y)) continue;
          const c = inBar(x, y) ? fg : bg;
          a++;
          acc[0] += c[0];
          acc[1] += c[1];
          acc[2] += c[2];
        }
      }
      const o = (py * size + pxl) * 4;
      if (a > 0) {
        px[o] = Math.round(acc[0] / a);
        px[o + 1] = Math.round(acc[1] / a);
        px[o + 2] = Math.round(acc[2] / a);
        px[o + 3] = Math.round((a / (ss * ss)) * 255);
      }
    }
  }
  return encodePng(size, size, px);
}

// ---------------------------------------------------------- Tabler SVG

/** Children of a Tabler outline SVG as [tag, attrs] (the empty frame path dropped). */
export function svgChildren(svg) {
  const body = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));
  const out = [];
  for (const m of body.matchAll(/<([a-z]+)\b([^>]*?)\/?>/g)) {
    const attrs = {};
    for (const a of m[2].matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) attrs[a[1]] = a[2];
    if (attrs.stroke === 'none') continue;
    if (!['path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse'].includes(m[1])) continue;
    out.push([m[1], attrs]);
  }
  return out;
}

// ------------------------------------------------------------ Chrome id

/** Chrome's extension id for a manifest "key" (base64 SPKI DER). */
export function chromeExtensionId(keyBase64) {
  const der = Buffer.from(keyBase64, 'base64');
  const hex = createHash('sha256').update(der).digest('hex').slice(0, 32);
  return [...hex].map((c) => String.fromCharCode('a'.charCodeAt(0) + parseInt(c, 16))).join('');
}

// ------------------------------------------------------------ manifest

/** Deep merge for manifests: objects merge, arrays and scalars replace. */
export function mergeManifest(base, over) {
  const out = { ...base };
  for (const [k, v] of Object.entries(over)) {
    if (v && typeof v === 'object' && !Array.isArray(v) && base[k] && typeof base[k] === 'object' && !Array.isArray(base[k])) {
      out[k] = mergeManifest(base[k], v);
    } else out[k] = v;
  }
  return out;
}

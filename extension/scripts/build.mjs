// Builds the extension: dist/chrome (service worker) and dist/firefox
// (event page) from one source tree. Node standard library only, so the
// build is reproducible from the repository (AMO asks for that).
//
//   node scripts/build.mjs [--target chrome|firefox|all] [--e2e]
//
// --e2e writes dist/<target>-e2e (dist/chrome-e2e for npm run test:e2e,
// dist/firefox-e2e for npm run test:firefox): the build plus host access to
// the local test site (http://127.0.0.1 and the test host names mapped to
// it; granted at install, so the end-to-end test needs no permission
// prompt) and test hooks in the background (a fake LectureFlow behind the
// native port, a recorder of cookies.getAll arguments).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { extractTokens, tokensCss, tokensJs, renderIcon, svgChildren, mergeManifest } from './lib.mjs';
import { bundleClassic } from './bundle.mjs';
import { checkProfile } from '../src/lib/profile.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const repo = path.resolve(root, '..');

function arg(name, def) {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : def;
}
const targetArg = arg('--target', 'all');
const e2e = process.argv.includes('--e2e');
const targets = targetArg === 'all' ? ['chrome', 'firefox'] : [targetArg];
for (const t of targets) if (!['chrome', 'firefox'].includes(t)) throw new Error(`unknown target ${t}`);
if (e2e && targets.length !== 1) throw new Error('--e2e builds one target: --target chrome or --target firefox');

const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const write = (p, data) => {
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, data);
};

function copyDir(from, to, skip = () => false) {
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const src = path.join(from, entry.name);
    const dst = path.join(to, entry.name);
    if (skip(src, entry)) continue;
    if (entry.isDirectory()) copyDir(src, dst, skip);
    else write(dst, fs.readFileSync(src));
  }
}

const pkg = readJson(path.join(root, 'package.json'));
const tokens = extractTokens(fs.readFileSync(path.join(repo, 'web', 'style.css'), 'utf8'));
const schema = readJson(path.join(root, 'schema', 'profile.schema.json'));

// Profiles: every one must pass; drafts are left out of the package.
const profileFiles = fs.readdirSync(path.join(root, 'profiles')).filter((f) => f.endsWith('.json')).sort();
const packaged = [];
for (const f of profileFiles) {
  const p = readJson(path.join(root, 'profiles', f));
  const errors = checkProfile(schema, p);
  if (errors.length) throw new Error(`profiles/${f}: ${errors.map((e) => `${e.path} ${e.message}`).join('; ')}`);
  if (`${p.id}.json` !== f) throw new Error(`profiles/${f}: file name must be ${p.id}.json`);
  if (!p.draft) packaged.push(f);
}

// Icons from the vendored Tabler SVGs, with their licence.
const tablerDir = path.join(root, 'src', 'vendor', 'tabler');
const icons = {};
for (const f of fs.readdirSync(tablerDir).filter((x) => x.endsWith('.svg')).sort()) {
  icons[f.replace(/\.svg$/, '')] = svgChildren(fs.readFileSync(path.join(tablerDir, f), 'utf8'));
}
const tablerLicense = fs.readFileSync(path.join(tablerDir, 'LICENSE'), 'utf8').trim().split(/\r?\n/).map((l) => `// ${l}`.trimEnd()).join('\n');
const iconsJs = [
  '// SPDX-License-Identifier: AGPL-3.0-or-later',
  '// Copyright (C) 2026 LectureFlow contributors. Licensed under the GNU AGPL v3 or later; see LICENSE.',
  '// Generated by scripts/build.mjs from src/vendor/tabler/*.svg (Tabler Icons,',
  '// @tabler/icons 3.49.0, outline). The path data is under the MIT licence:',
  '//',
  tablerLicense,
  '',
  `export const ICONS = ${JSON.stringify(icons)};`,
  '',
].join('\n');

function build(target, outName, testBuild) {
  const out = path.join(root, 'dist', outName);
  fs.rmSync(out, { recursive: true, force: true });
  // Sources, without the SVG originals (they become ui/icons.js) and the
  // fixture replay (CI only).
  const replay = path.join(root, 'src', 'lib', 'replay.js');
  copyDir(path.join(root, 'src'), out, (src) => (src.startsWith(tablerDir + path.sep) && src.endsWith('.svg')) || src === replay);
  copyDir(path.join(root, '_locales'), path.join(out, '_locales'));
  write(path.join(out, 'schema', 'profile.schema.json'), fs.readFileSync(path.join(root, 'schema', 'profile.schema.json')));
  for (const f of packaged) write(path.join(out, 'profiles', f), fs.readFileSync(path.join(root, 'profiles', f)));
  write(path.join(out, 'profiles', 'index.json'), JSON.stringify({ profiles: packaged }, null, 2) + '\n');
  write(path.join(out, 'profiles', 'LICENSE'), fs.readFileSync(path.join(root, 'profiles', 'LICENSE')));
  write(path.join(out, 'ui', 'tokens.css'), tokensCss(tokens));
  write(path.join(out, 'ui', 'tokens.js'), tokensJs(tokens));
  write(path.join(out, 'ui', 'icons.js'), iconsJs);
  write(
    path.join(out, 'build-info.js'),
    [
      '// SPDX-License-Identifier: AGPL-3.0-or-later',
      '// Copyright (C) 2026 LectureFlow contributors. Licensed under the GNU AGPL v3 or later; see LICENSE.',
      '// Generated by scripts/build.mjs. Do not edit.',
      `export const BUILD = Object.freeze(${JSON.stringify({ target, version: pkg.version, e2e: testBuild })});`,
      '',
    ].join('\n'),
  );
  // The in-page UI's styles, for its shadow roots: the tokens (on :host,
  // light and dark), the shared base and card styles, its own.
  const SPDX = '// SPDX-License-Identifier: AGPL-3.0-or-later\n// Copyright (C) 2026 LectureFlow contributors. Licensed under the GNU AGPL v3 or later; see LICENSE.\n';
  const inpageCss = [
    tokensCss(tokens).replace(/:root\b/g, ':host'),
    fs.readFileSync(path.join(root, 'src', 'ui', 'base.css'), 'utf8'),
    fs.readFileSync(path.join(root, 'src', 'ui', 'card.css'), 'utf8'),
    fs.readFileSync(path.join(root, 'src', 'content', 'inpage.css'), 'utf8'),
  ].join('\n');
  write(path.join(out, 'ui', 'inpage-css.js'), `${SPDX}// Generated by scripts/build.mjs. Do not edit.\nexport const INPAGE_CSS = ${JSON.stringify(inpageCss)};\n`);
  // Content scripts cannot be modules: the in-page entry points become one
  // classic script (scripts/bundle.mjs).
  const inpageJs = path.join(out, 'content', 'inpage.js');
  write(inpageJs, bundleClassic(inpageJs, { banner: `${SPDX}// Generated by scripts/build.mjs from src/content/inpage.js and the modules it imports. Do not edit.\n` }));
  fs.rmSync(path.join(out, 'content', 'inpage.css'), { force: true });
  for (const size of [16, 32, 48, 128]) {
    write(path.join(out, 'icons', `icon-${size}.png`), renderIcon(size, tokens.light['--accent'], tokens.light['--text-on-accent']));
  }
  let manifest = mergeManifest(readJson(path.join(root, 'manifest.base.json')), readJson(path.join(root, `manifest.${target}.json`)));
  manifest.version = pkg.version;
  // The e2e test site: 127.0.0.1, plus host names the test browser maps to
  // it (--host-resolver-rules) so a profile's hosts can be exercised; and
  // three do-not-handle sites (test/e2e/blocklist.test.mjs), granted here
  // as no user can grant them, to show the extension still leaves them
  // alone when the browser would let it in.
  if (testBuild) {
    manifest = {
      ...manifest,
      host_permissions: ['http://127.0.0.1/*', 'http://*.lf-e2e.test/*', 'http://*.cloud.panopto.eu/*', 'http://*.youtube-nocookie.com/*', 'http://*.edx.org/*', 'http://*.linkedin.com/*'],
    };
  }
  write(path.join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  return out;
}

for (const t of targets) {
  const out = e2e ? build(t, `${t}-e2e`, true) : build(t, t, false);
  console.log(`built ${path.relative(root, out)}`);
}

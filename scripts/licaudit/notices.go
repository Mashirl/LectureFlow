// RenderNotices produces THIRD_PARTY_NOTICES.md. The output is
// deterministic (no timestamps, sorted), so a diff means the third-party
// content changed.
func RenderNotices(r *Report) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	w("# Third-Party Notices / 第三方声明\n\n")
	w("<!-- Generated by `go run ./scripts/licaudit` (make.ps1 audit). Do not edit by hand. -->\n\n")
	w("LectureFlow is licensed under the GNU Affero General Public License v3.0 or later (see `LICENSE`).\n")
	w("It includes or downloads the third-party components listed below, each under its own license.\n\n")
	w("LectureFlow 以 GNU AGPL-3.0-or-later 许可发布（见 `LICENSE`）。下列第三方组件随应用分发或由组件管理器下载，各自遵循其许可证。\n\n")

	if len(r.Violations) > 0 {
		w("## Unresolved audit findings / 未解决的审计问题\n\n")
		w("The license audit failed. These items must be resolved before a release:\n\n")
		for _, v := range r.Violations {
			w("- %s\n", mdEscape(v.String()))
		}
		w("\n")
	}

	sections := []struct {
		kind, title, intro string
		userFetched        bool
	}{
		{KindGo, "1. Go modules (compiled into the LectureFlow server)", "Modules linked into `lectureflow` for Windows, macOS and Linux (`go list -deps`). Their license texts are reproduced in Appendix A.", false},
		{KindVendor, "2. Front-end third-party code (`web/vendor`)", "Copied unchanged into the web front end. License texts in Appendix A.", false},
		{KindNPM, "3. Desktop shell (Electron, npm)", "Runtime npm packages of `desktop/` (`desktop/package-lock.json`); build-only devDependencies are not shipped and not listed.", false},
		{KindPython, "4. Python packages of the components", "Installed by the component manager (uv) into each component's virtual environment. Each package's license files stay in its `*.dist-info` directory inside the installed component.", false},
		{KindModel, "5. Speech recognition models", "Downloaded by the component manager. Listed from the component manifest (`packaging/components/components.json`), each pinned to a repository revision (Version column); each model's license is in its source repository.", false},
		{KindBinary, "6. Bundled binaries", "Programs shipped next to the server. Their license texts ship alongside the binaries.", false},
		{KindPython, "7. Downloaded on your computer by the component manager, not distributed with LectureFlow / 由组件管理器在你的电脑上下载、不随本程序分发的组件",
			"These Python packages are not part of the LectureFlow installer or of any LectureFlow download. When you install a component that needs them, the component manager downloads them on your computer from PyPI (or the mirror you chose), pinned by the component's lock file, into that component's own Python environment, which runs in a separate process. Their licenses, listed here, are between you and their authors; LectureFlow does not publish offline component archives that contain them. LectureFlow's combination with these libraries is covered by the additional permission under section 7 of the GNU AGPL in `LICENSE-EXCEPTION.md`; that permission does not change their licenses, and LectureFlow still does not distribute them.\n\n" +
				"这些 Python 包不包含在 LectureFlow 安装包或任何 LectureFlow 下载中。安装需要它们的组件时，组件管理器按锁定文件从 PyPI（或你选择的镜像）把它们下载到你的电脑上，装入该组件独立的 Python 环境，并在独立进程中运行。它们的许可证如下；LectureFlow 不发布包含这些包的离线组件压缩包。LectureFlow 与这些库的组合使用依据 `LICENSE-EXCEPTION.md` 中 GNU AGPL 第 7 条的附加许可；该附加许可不改变它们的许可证，LectureFlow 也仍然不分发它们。", true},
	}
	for _, s := range sections {
		var cs []Component
		for _, c := range r.Components {
			if c.Kind == s.kind && c.UserFetched == s.userFetched {
				cs = append(cs, c)
			}
		}
		w("## %s\n\n%s\n\n", s.title, s.intro)
		for _, sk := range r.Skipped {
			if skippedKind(sk) == s.kind && !s.userFetched {
				w("_Not audited: %s._\n\n", mdEscape(sk))
			}
		}
		if len(cs) == 0 {
			w("_None._\n\n")
			continue
		}
		groupCol := map[string]string{KindPython: "Components", KindBinary: "Component / platforms"}[s.kind]
		if groupCol != "" {
			w("| Name | Version | License | %s | Source | Note |\n|---|---|---|---|---|---|\n", groupCol)
		} else {
			w("| Name | Version | License | Source | Note |\n|---|---|---|---|---|\n")
		}
		for _, c := range cs {
			note := c.Note
			switch {
			case c.UserFetched:
				note = strings.TrimSpace(note + " Not distributed by LectureFlow: " + c.Allowed)
			case c.Allowed != "":
				note = strings.TrimSpace(note + " Accepted by allowlist: " + c.Allowed)
			}
			lic := c.License
			if lic == "" {
				lic = "(unknown)"
			}
			if groupCol != "" {
				w("| %s | %s | %s | %s | %s | %s |\n", mdEscape(c.Name), mdEscape(c.Version), mdEscape(lic), mdEscape(c.Group), mdEscape(c.Source), mdEscape(note))
			} else {
				w("| %s | %s | %s | %s | %s |\n", mdEscape(c.Name), mdEscape(c.Version), mdEscape(lic), mdEscape(c.Source), mdEscape(note))
			}
		}
		w("\n")
		if s.kind == KindBinary {
			renderBinaryDetails(w, cs)
		}
	}

	renderMedia(w, r)
	renderReferences(w, r)
	renderTools(w, r)
	renderExtension(w, r)

	// Appendix A: identical texts are printed once with every user listed.
	type group struct {
		text  string
		users []string
	}
	groups := map[[32]byte]*group{}
	var order [][32]byte
	for _, c := range r.Components {
		for _, t := range c.Texts {
			norm := strings.TrimSpace(strings.ReplaceAll(t.Text, "\r\n", "\n"))
			if norm == "" {
				continue
			}
			k := sha256.Sum256([]byte(norm))
			g := groups[k]
			if g == nil {
				g = &group{text: norm}
				groups[k] = g
				order = append(order, k)
			}
			label := c.Name
			if c.Version != "" {
				label += " " + c.Version
			}
			g.users = append(g.users, label+" ("+t.File+")")
		}
	}
	w("## Appendix A: License texts and notices\n\n")
	if len(order) == 0 {
		w("_None._\n\n")
	}
	for i, k := range order {
		g := groups[k]
		sort.Strings(g.users)
		fence := "````"
		for strings.Contains(g.text, fence) {
			fence += "`"
		}
		w("### A.%d\n\nUsed by: %s\n\n%stext\n%s\n%s\n\n", i+1, mdEscape(strings.Join(g.users, "; ")), fence, g.text, fence)
	}
	w("## Appendix B: Where the other license texts are\n\n")
	w("- Python packages: `*.dist-info/licenses/` (or `*.dist-info/LICENSE*`) inside each installed component; upstream at the source links above.\n")
	w("- Python packages whose wheel carries no license file (for example mlx-whisper): the text is reproduced in Appendix A from a copy kept in `packaging/licenses/texts/`, pinned to an upstream commit (see the package note in section 4).\n")
	w("- Upstreams reimplemented from their protocol (section 9): copies of their license files are kept in `packaging/licenses/texts/` and reproduced in Appendix A.\n")
	w("- Models: the license file or model card of each source repository listed in section 5.\n")
	w("- Programs downloaded from their vendor (section 10): the license files inside the installed tool (`components/{id}/{version}/tool/`; for the Google Cloud CLI its `LICENSE` and the license files of the parts it bundles).\n")
	w("- Bundled binaries: the license files shipped next to each binary (section 6).\n")
	w("- Electron: `LICENSE` and `LICENSES.chromium.html` in the application directory.\n")
	w("- Browser extension (section 11): `vendor/NOTICE` and the license file of each package next to it, inside the extension package (`extension/src/vendor/` in the repository); the Tabler Icons notice is also at the top of `ui/icons.js`.\n")
	return b.String()
}

func skippedKind(s string) string {
	switch {
	case strings.HasPrefix(s, "Go "):
		return KindGo
	case strings.HasPrefix(s, vendorDir):
		return KindVendor
	case strings.HasPrefix(s, npmLockFile):
		return KindNPM
	case strings.HasPrefix(s, componentsDir):
		return KindPython
	case strings.HasPrefix(s, binariesFile):
		return KindBinary
	case strings.HasPrefix(s, mediaFile):
		return KindMedia
	case strings.HasPrefix(s, refsFile):
		return KindReference
	case strings.HasPrefix(s, "extension/"):
		return KindExtension
	}
	return ""
}

func mdEscape(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	return strings.ReplaceAll(strings.ReplaceAll(s, "\r", " "), "\n", " ")
}

func componentsOf(r *Report, kind string) []Component {
	var cs []Component
	for _, c := range r.Components {
		if c.Kind == kind {
			cs = append(cs, c)
		}
	}
	return cs
}

func skippedNote(w func(string, ...any), r *Report, kind string) {
	for _, sk := range r.Skipped {
		if skippedKind(sk) == kind {
			w("_Not audited: %s._\n\n", mdEscape(sk))
		}
	}
}

// renderMedia writes section 8: media files shipped with LectureFlow.
func renderMedia(w func(string, ...any), r *Report) {
	w("## 8. Bundled media / 随包分发的媒体文件\n\n")
	w("Media files shipped with LectureFlow (`assets/`, listed in `packaging/licenses/media.json`).\n\n")
	w("随 LectureFlow 分发的媒体文件（`assets/`，清单见 `packaging/licenses/media.json`）。\n\n")
	skippedNote(w, r, KindMedia)
	cs := componentsOf(r, KindMedia)
	if len(cs) == 0 {
		w("_None._\n\n")
		return
	}
	w("| File | Work | License | Sources | Note |\n|---|---|---|---|---|\n")
	for _, c := range cs {
		work, note := "", c.Note
		if m := c.Media; m != nil {
			work = strings.TrimSpace(m.Title + ". " + m.Creator)
			if m.Published != "" {
				work += ". " + m.Published
			}
			basis := m.LicenseBasis
			if m.LicenseURL != "" {
				basis = strings.TrimSpace(basis + " (" + m.LicenseURL + ")")
			}
			note = strings.TrimSpace(basis + " " + note)
		}
		if c.Allowed != "" {
			note = strings.TrimSpace(note + " Accepted by allowlist: " + c.Allowed)
		}
		lic := c.License
		if lic == "" {
			lic = "(unknown)"
		}
		w("| %s | %s | %s | %s | %s |\n", mdEscape(c.Name), mdEscape(work), mdEscape(lic), mdEscape(c.Source), mdEscape(note))
	}
	w("\n")
}

// renderReferences writes section 9: upstreams whose protocol was
// reimplemented without copying code (SPEC-v3 V14.6).
func renderReferences(w func(string, ...any), r *Report) {
	w("## 9. Upstreams reimplemented from their protocol, no code copied / 参照其协议重新实现、未复制代码的上游\n\n")
	w("LectureFlow contains no code from these projects. Parts of LectureFlow were written to follow their protocol; their copyright and license notices are kept here, and their license texts are in Appendix A.\n\n")
	w("LectureFlow 不包含这些项目的代码。下列部分参照它们的协议重新编写；这里保留其版权与许可声明，许可证全文见附录 A。\n\n")
	skippedNote(w, r, KindReference)
	cs := componentsOf(r, KindReference)
	if len(cs) == 0 {
		w("_None._\n\n")
		return
	}
	for _, c := range cs {
		w("### %s %s\n\n", mdEscape(c.Name), mdEscape(c.Version))
		w("- License: %s\n", mdEscape(c.License))
		if e := c.Ref; e != nil {
			for _, cr := range e.Copyright {
				if strings.TrimSpace(cr) != "" {
					w("- %s\n", mdEscape(cr))
				}
			}
			w("- Source: %s\n", mdEscape(c.Source))
			if e.Artifact != "" {
				w("- Read: %s\n", mdEscape(e.Artifact))
			}
			w("- Referenced for: %s\n", mdEscape(e.Used))
			w("- Used by: %s\n", mdEscape(e.UsedBy))
			w("- Changes: %s\n", mdEscape(e.Changes))
			if e.Details != "" {
				w("- Details: `%s`\n", mdEscape(e.Details))
			}
			if e.LicenseTextSource != "" {
				w("- License text: %s\n", mdEscape(e.LicenseTextSource))
			}
		}
		if c.Allowed != "" {
			w("- Accepted by allowlist: %s\n", mdEscape(c.Allowed))
		}
		w("\n")
	}
}

// renderTools writes section 10: programs the component manager downloads
// from their vendor on the user's computer (tools.go).
func renderTools(w func(string, ...any), r *Report) {
	w("## 10. Programs downloaded from their vendor on your computer, not distributed with LectureFlow / 由组件管理器从官方下载到你的电脑、不随本程序分发的程序\n\n")
	w("When you install one of these components, the component manager downloads the vendor's own archive from the vendor's server, checks its SHA-256 against the component manifest and unpacks it; LectureFlow runs it as a separate program. It is not part of the LectureFlow installer or of any LectureFlow download, and LectureFlow publishes no offline archive of it. Its license, listed here, is between you and its vendor; the parts the vendor bundles in its archive keep their own licenses (see the note and the license files inside the installed tool).\n\n")
	w("安装这些组件时，组件管理器从官方服务器下载官方压缩包，按组件清单核对 SHA-256 后解压，LectureFlow 把它作为独立程序运行。它们不包含在 LectureFlow 安装包或任何 LectureFlow 下载中，LectureFlow 也不发布它们的离线压缩包。其许可证如下，由你与其发布者之间约定；官方压缩包内附带的部分各自遵循其许可证（见备注与安装目录中的许可证文件）。\n\n")
	cs := componentsOf(r, KindTool)
	if len(cs) == 0 {
		w("_None._\n\n")
		return
	}
	w("| Name | Version | License | Platforms | Source | Note |\n|---|---|---|---|---|---|\n")
	for _, c := range cs {
		note := c.Note
		if c.Allowed != "" {
			note = strings.TrimSpace(note + " Accepted by allowlist: " + c.Allowed)
		}
		lic := c.License
		if lic == "" {
			lic = "(unknown)"
		}
		w("| %s | %s | %s | %s | %s | %s |\n", mdEscape(c.Name), mdEscape(c.Version), mdEscape(lic), mdEscape(c.Group), mdEscape(c.Source), mdEscape(note))
	}
	w("\n")
}

// renderExtension writes section 11: third-party content of the browser
// extension's packages (extension.go).
func renderExtension(w func(string, ...any), r *Report) {
	w("## 11. Browser extension / 浏览器扩展\n\n")
	w("Third-party files inside the browser extension's packages (Chrome, Edge, Firefox): copied unchanged from npm into `extension/src/vendor`, registered in `packaging/licenses/extension.json`, and shipped with `vendor/NOTICE` and their license texts (Appendix A). The extension's own code is under the AGPL like the rest of LectureFlow. Its platform profiles and detection fixtures (`extension/profiles`, `extension/fixtures`) are dedicated to the public domain under CC0-1.0 (`extension/profiles/LICENSE`). Its development tools (Playwright, for the end-to-end tests) are not shipped and not listed.\n\n")
	w("浏览器扩展安装包（Chrome、Edge、Firefox）中的第三方文件：从 npm 原样复制到 `extension/src/vendor`，登记在 `packaging/licenses/extension.json`，与 `vendor/NOTICE` 及各自的许可证全文一起分发（附录 A）。扩展自身的代码与 LectureFlow 其他部分一样以 AGPL 发布；平台对策文件与探测报告样例（`extension/profiles`、`extension/fixtures`）以 CC0-1.0 贡献到公有领域（`extension/profiles/LICENSE`）。开发工具（端到端测试用的 Playwright）不随扩展分发，不在此列出。\n\n")
	skippedNote(w, r, KindExtension)
	cs := componentsOf(r, KindExtension)
	if len(cs) == 0 {
		w("_None._\n\n")
		return
	}
	w("| Name | Version | License | Shipped as | Source | Note |\n|---|---|---|---|---|---|\n")
	for _, c := range cs {
		note := c.Note
		if c.Allowed != "" {
			note = strings.TrimSpace(note + " Accepted by allowlist: " + c.Allowed)
		}
		lic := c.License
		if lic == "" {
			lic = "(unknown)"
		}
		w("| %s | %s | %s | %s | %s | %s |\n", mdEscape(c.Name), mdEscape(c.Version), mdEscape(lic), mdEscape(c.Group), mdEscape(c.Source), mdEscape(note))
	}
	w("\n")
}
